#[cfg(test)]
mod wifi_grub_tests {
    use super::*;

    fn closure(root: &'static str) -> BTreeSet<&'static str> {
        let specs = package_specs();
        let by_name = specs
            .iter()
            .map(|spec| (spec.name, spec))
            .collect::<BTreeMap<_, _>>();
        let mut pending = vec![root];
        let mut result = BTreeSet::new();
        while let Some(name) = pending.pop() {
            if !result.insert(name) {
                continue;
            }
            let spec = by_name
                .get(name)
                .unwrap_or_else(|| panic!("missing package {name}"));
            pending.extend(spec.depends.iter().copied());
        }
        result
    }
    #[test]
    fn wifi_and_bootloader_runtime_dependencies_are_complete() {
        let specs = package_specs();
        let network = specs.iter().find(|p| p.name == "network-manager").unwrap();
        assert!(network.depends.contains(&"wpasupplicant"));
        let supplicant = specs.iter().find(|p| p.name == "wpasupplicant").unwrap();
        for dependency in [
            "libnl-3-200",
            "libnl-genl-3-200",
            "libssl3t64",
            "libdbus-1-3",
        ] {
            assert!(supplicant.depends.contains(&dependency));
        }
        assert!(
            specs
                .iter()
                .find(|p| p.name == "mattos-installer")
                .unwrap()
                .depends
                .contains(&"grub-efi-amd64")
        );
    }

    #[test]
    fn qt_foundation_packages_preserve_module_and_wayland_ownership() {
        let specs = package_specs();
        let spec = |name| specs.iter().find(|spec| spec.name == name).unwrap();
        let base = spec("qt6-base");
        assert_eq!(base.source_component, "qtbase");
        for dependency in [
            "libegl1",
            "libopengl0",
            "libxkbcommon0",
            "libwayland-client0",
            "libwayland-cursor0",
            "libwayland-egl1",
        ] {
            assert!(base.depends.contains(&dependency));
        }
        assert_eq!(spec("qt6-svg").source_component, "qtsvg");
        assert_eq!(spec("qt6-svg").depends, &["qt6-base"]);
        let wayland = spec("qt6-wayland");
        assert_eq!(wayland.source_component, "qtwayland");
        for dependency in [
            "qt6-base",
            "libwayland-client0",
            "libwayland-server0",
            "libxkbcommon0",
        ] {
            assert!(wayland.depends.contains(&dependency));
        }
    }

    #[test]
    fn plasma_wayland_workspace_owns_session_manager_runtime_closure() {
        let specs = package_specs();
        let workspace = specs
            .iter()
            .find(|spec| spec.name == "plasma-workspace")
            .unwrap();
        assert!(workspace.depends.contains(&"libice6"));
        assert!(workspace.depends.contains(&"libsm6"));
        assert!(workspace.depends.contains(&"libx11-6"));
        assert!(workspace.depends.contains(&"libxi6"));
        assert!(workspace.depends.contains(&"libxrender1"));
        assert!(workspace.depends.contains(&"libxtst6"));
        assert!(workspace.depends.contains(&"libxcursor1"));
        assert!(workspace.depends.contains(&"libxft2"));
        // These QML applets are loaded by Qt at runtime, so their ICU
        // DT_NEEDED entries are not visible to the Plasma meta-package unless
        // the workspace package declares the source-owned ICU runtime itself.
        assert!(workspace.depends.contains(&"libicu78"));
        assert!(workspace.depends.contains(&"kscreenlocker"));
        let locker = specs
            .iter()
            .find(|spec| spec.name == "kscreenlocker")
            .expect("workspace's declared screen-locker runtime package exists");
        assert_eq!(locker.source_component, "kscreenlocker");
        assert!(locker.depends.contains(&"plasma-framework"));
        assert!(locker.depends.contains(&"breeze-icons"));
        assert!(locker.depends.contains(&"libpam0g"));
        assert_eq!(
            specs
                .iter()
                .find(|spec| spec.name == "libice6")
                .unwrap()
                .source_component,
            "x11-compat"
        );
        let libsm = specs.iter().find(|spec| spec.name == "libsm6").unwrap();
        assert_eq!(libsm.source_component, "x11-compat");
        assert!(libsm.depends.contains(&"libice6"));
        for name in [
            "libxi6",
            "libxrender1",
            "libxtst6",
            "libxcursor1",
            "libxft2",
        ] {
            assert_eq!(
                specs
                    .iter()
                    .find(|spec| spec.name == name)
                    .unwrap()
                    .source_component,
                "x11-compat"
            );
        }
    }

    #[test]
    fn plasma_profile_closes_dynamic_launcher_clock_and_audio_runtime_dependencies() {
        let specs = package_specs();
        let spec = |name| specs.iter().find(|spec| spec.name == name).unwrap();

        assert!(spec("plasma-workspace").depends.contains(&"libicu78"));
        assert!(spec("plasma-pa").depends.contains(&"libpulse0"));

        let installed_profile = closure("mattos-plasma");
        for runtime in ["libicu78", "libpulse0"] {
            assert!(
                installed_profile.contains(runtime),
                "mattos-plasma must install {runtime} for dynamically loaded QML applets"
            );
        }
    }

    #[test]
    fn font_runtime_and_discovery_packages_have_explicit_ownership() {
        let specs = package_specs();
        let spec = |name| specs.iter().find(|spec| spec.name == name).unwrap();
        let freetype = spec("libfreetype6");
        assert_eq!(freetype.source_component, "freetype");
        assert!(freetype.depends.contains(&"zlib1g"));
        let fontconfig = spec("libfontconfig1");
        assert_eq!(fontconfig.source_component, "fontconfig");
        for dependency in ["libc6", "libexpat1", "libfreetype6"] {
            assert!(fontconfig.depends.contains(&dependency));
        }
        let tools = spec("fontconfig");
        assert_eq!(tools.source_component, "fontconfig");
        assert!(tools.depends.contains(&"libfontconfig1"));
        let fonts = spec("fonts-fira");
        assert_eq!(fonts.source_component, "pop-fonts");
        assert!(fonts.depends.contains(&"fontconfig"));
        assert!(spec("plasma-desktop").depends.contains(&"fonts-fira"));
    }

    #[test]
    fn installed_profiles_have_distinct_deterministic_closures() {
        let cli = closure("mattos-cli");
        for required in [
            "systemd",
            "linux-modules-7.2.0-rc5-mattos",
            "linux-firmware",
            "network-manager",
            "apt",
            "dpkg",
            "openssh-server",
            "grub-efi-amd64",
            "mattos-sudo-rs",
        ] {
            assert!(cli.contains(required), "CLI profile misses {required}");
        }
        for forbidden in [
            "qt6-base",
            "kwin",
            "plasma-workspace",
            "plasma-desktop",
            "mattos-plasma-theme",
            "libegl-mesa0",
            "greetd",
            "plasma-login-manager",
            "mattos-plasma-live",
            "dolphin",
            "konsole",
            "systemsettings",
            "mattos-installer",
            "calamares",
        ] {
            assert!(!cli.contains(forbidden), "CLI profile contains {forbidden}");
        }

        let plasma = closure("mattos-plasma");
        let base = closure("mattos-base");
        assert!(base.iter().all(|package| plasma.contains(package)));
        for required in [
            "qt6-base",
            "qt6-declarative",
            "kwin",
            "kwin-aurorae",
            "plasma-framework",
            "plasma-workspace",
            "plasma-desktop",
            "libegl-mesa0",
            "plasma-login-manager",
            "kf6-kpackage",
            "kf6-kdeclarative",
            "kf6-kirigami",
            "kf6-qqc2-desktop-style",
            "kactivitymanagerd",
            "kglobalacceld",
            "plasma-nm",
            "plasma-pa",
            "powerdevil",
            "dolphin",
            "konsole",
            "kate",
            "ark",
            "spectacle",
            "plasma-systemmonitor",
            "systemsettings",
        ] {
            assert!(
                plasma.contains(required),
                "Plasma profile misses {required}"
            );
        }
        assert!(
            !plasma.contains("mattos-installer"),
            "Plasma profile contains the live-only installer"
        );
        assert!(
            !plasma.contains("greetd"),
            "installed Plasma profile retains greetd"
        );
        assert!(
            !plasma.contains("mattos-plasma-live"),
            "installed Plasma profile contains live-only greetd integration"
        );
        assert!(
            !plasma.contains("calamares"),
            "Plasma profile contains the live installer"
        );
        assert!(plasma.len() > cli.len() + 50);
    }

    #[test]
    fn aurorae_decoration_is_declared_for_the_plasma_profile_and_matches_source() {
        let specs = package_specs();
        let aurorae = specs.iter().find(|spec| spec.name == "kwin-aurorae").unwrap();
        assert_eq!(aurorae.source_component, "aurorae");
        assert!(aurorae.depends.contains(&"kf6-kdecoration"));
        assert!(package_specs().iter().find(|spec| spec.name == "kwin").unwrap().depends.contains(&"kwin-aurorae"));
        assert!(closure("mattos-plasma").contains("kwin-aurorae"));
    }
}

