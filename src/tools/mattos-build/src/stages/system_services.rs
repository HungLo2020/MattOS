fn build_polkit(repo_root: &Path) -> Result<()> {
    build_meson_runtime(
        repo_root,
        "polkit",
        "src/system/security/polkit",
        &[
            "glib",
            "pcre2",
            "zlib",
            "systemd",
            "dbus",
            "duktape",
            "linux-pam",
            "libffi",
        ],
        &[
            "--prefix=/usr",
            "--libdir=lib/x86_64-linux-gnu",
            "-Dtests=false",
            "-Dman=false",
            "-Dgtk_doc=false",
            "-Dexamples=false",
            "-Dintrospection=false",
            "-Dgettext=false",
            "-Dsession_tracking=logind",
            "-Dauthfw=pam",
            "-Dos_type=debian",
            "-Dpolkitd_uid=197",
        ],
        "usr/lib/x86_64-linux-gnu/libpolkit-agent-1.so.0",
        &[],
    )
}

fn build_networkmanager(repo_root: &Path) -> Result<()> {
    build_meson_runtime(
        repo_root,
        "networkmanager",
        "src/system/network/NetworkManager",
        &[
            "glib",
            "pcre2",
            "systemd",
            "dbus",
            "polkit",
            "iproute2",
            "util-linux",
            "libndp",
            "zlib",
            "readline",
            "ncurses",
            "libffi",
        ],
        &[
            "--prefix=/usr",
            "--libdir=lib/x86_64-linux-gnu",
            "-Dtests=no",
            "-Ddocs=false",
            "-Dman=false",
            "-Dpolkit=true",
            "-Dnmcli=true",
            "-Dnmtui=false",
            "-Dwifi=true",
            "-Dmodem_manager=false",
            "-Dovs=false",
            "-Dclat=false",
            "-Dconcheck=false",
            "-Dppp=false",
            "-Dlibpsl=false",
            "-Dcrypto=null",
            "-Dsession_tracking=systemd",
            "-Dconfig_dns_rc_manager_default=symlink",
            "-Dconfig_auth_polkit_default=true",
            "-Dintrospection=false",
            "-Dselinux=false",
            "-Dlibaudit=no",
            "-Dnm_cloud_setup=false",
            "-Dnbft=false",
            "-Dsystemdsystemunitdir=/usr/lib/systemd/system",
            "-Ddbus_conf_dir=/usr/share/dbus-1/system.d",
        ],
        "usr/sbin/NetworkManager",
        &[],
    )
}
